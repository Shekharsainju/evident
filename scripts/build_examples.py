"""Task 22 examples/: one complete run through the real pipeline, from a fixed profile and job.

Nothing is written unless the run finishes, both outputs pass post-render verification and
the inflated claim is really rejected. A failed build leaves the old examples untouched.
Prints counts and IDs only, never CV text.

Usage:
  uv run python scripts/build_examples.py
"""

from __future__ import annotations

import json
import shutil
import tempfile
from datetime import UTC, datetime
from pathlib import Path

from pydantic import BaseModel

from evident.contracts.enums import ClaimOutcome, FactKind, FactStatus, OutputType, RunState
from evident.contracts.facts import FactRef, FactVersion
from evident.contracts.validation import ClaimValidation
from evident.errors import StageError
from evident.eval.assets import JOB_SCREENSHOT, cv_photo_path
from evident.models.adapter import ModelAdapter
from evident.models.router import build_adapter
from evident.review.actions import confirm
from evident.runs import RunService
from evident.settings import LOCAL_OWNER_ID, Settings, load_model_config
from evident.store.files import FileRepository

RESULTS = Path("experiments/a3-slice/RESULTS.md")
OUTPUT_FILES = {OutputType.visual_profile: ["profile.pdf", "profile.html"],
                OutputType.interview_deck: ["deck.pptx"]}
EXPECTED_FILES = [
    "input_cv_photo.jpg", "job_ad_screenshot.png", "facts.json", "coverage.json", "coverage.md",
    "profile.pdf", "profile.html", "deck.pptx", "validation_report.json",
    "inflated_claim_rejected.md", "RESULTS.md", "README.md",
]
FOLDER_README = """# Example run

One complete run of the CV Builder, generated by `scripts/build_examples.py` from {profile}
(template {template}). Everything here is synthetic: the CV, the job ad and the person are
fictional, and the outputs carry the marker text "Synthetic profile, A3 testing".

Facts were confirmed automatically for repeatability. In the UI a person reviews each fact.

| File | What it is |
|---|---|
| `input_cv_photo.jpg` | The simulated phone photo of the CV that the run started from |
| `job_ad_screenshot.png` | The job ad screenshot the CV was graded against |
| `facts.json` | The facts extracted from the photo, all confirmed |
| `coverage.json` | The graded coverage matrix |
| `coverage.md` | The same matrix as a readable table |
| `profile.pdf` | The validated visual profile, which passed post-render verification |
| `profile.html` | The HTML the PDF was printed from |
| `deck.pptx` | The validated interview deck, which passed post-render verification |
| `validation_report.json` | The Layer 1 and judge result for every claim |
| `inflated_claim_rejected.md` | An inflated claim being rejected, with the rule or verdict |
| `RESULTS.md` | A copy of the evaluation results |
"""


def inflated_text(title: str) -> str:
    return f"Led the production deployment of {title}"


def _dump(items: list[BaseModel]) -> str:
    return json.dumps([json.loads(i.model_dump_json()) for i in items], indent=2) + "\n"


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _coverage_table(rows: list[dict[str, str]]) -> str:
    lines = ["# Coverage matrix", "", "| Requirement | Category | Grade | Rationale |",
             "|---|---|---|---|"]
    lines += [f"| {_cell(r['text'])} | {r['category']} | {r['grade']} | {_cell(r['rationale'])} |"
              for r in rows]
    return "\n".join(lines) + "\n"


def _inflated_report(text: str, fact: FactVersion, result: ClaimValidation) -> str:
    lines = ["# An inflated claim being rejected", "",
             f"**Claim:** {text}", "",
             f"**Cited fact:** `{fact.fact_id}@{fact.version}`: {fact.text}", "",
             f"**Outcome:** {result.outcome.value}", "",
             "## Layer 1", ""]
    if result.layer1.failures:
        lines += ["| Rule | Phrase | Detail |", "|---|---|---|"]
        lines += [f"| {_cell(f.rule)} | {_cell(f.phrase)} | {_cell(f.detail)} |"
                  for f in result.layer1.failures]
    else:
        lines.append("No Layer 1 rule failed.")
    lines += ["", "## Judge", ""]
    if result.judge is not None:
        lines += [f"- Model: `{result.judge_model}`",
                  f"- Verdict: {result.judge.verdict.value}",
                  f"- Offending phrase: {result.judge.offending_phrase}",
                  f"- Confidence: {result.judge.confidence}"]
    else:
        lines.append(f"No verdict: {result.judge_error}")
    return "\n".join(lines) + "\n"


def _inflatable_fact(facts: list[FactVersion]) -> FactVersion:
    for fact in facts:
        if fact.kind is FactKind.project and fact.attributes.title:
            return fact
    raise SystemExit("Stopped: the run has no confirmed project to inflate.")


def _stop_unless_passed(service: RunService, run_id: str) -> None:
    run = service.repo.get_run(LOCAL_OWNER_ID, run_id)
    if run is None or run.state is not RunState.done:
        reason = run.error or run.state.value if run is not None else "missing"
        raise SystemExit(f"Stopped: the run did not finish ({reason}).")
    outs = [service.repo.get_output(LOCAL_OWNER_ID, oid) for oid in run.output_ids]
    if sorted(o.output_type.value for o in outs if o is not None) != sorted(OutputType):
        raise SystemExit("Stopped: the run did not produce both outputs.")
    for out in outs:
        if out is None or out.post_render is None or not out.post_render.passed:
            kind = out.output_type.value if out is not None else "output"
            raise SystemExit(f"Stopped: {kind} did not pass post-render verification.")
        print(f"{out.output_type.value}: post-render passed, {len(out.claim_ids)} claims")


def build_examples(
    out: Path = Path("examples"),
    profile: str = "student_profile_03",
    template: str = "sidebar",
    job: str = "screenshot",
    *,
    adapter: ModelAdapter | None = None,
    settings: Settings | None = None,
) -> None:
    settings = settings or Settings()
    if adapter is None and not settings.gemini_api_key.get_secret_value():
        raise SystemExit("Stopped: set GEMINI_API_KEY in .env first (see README.md).")
    adapter = adapter or build_adapter(settings, load_model_config())
    repo = FileRepository(settings.data_dir)
    service = RunService(repo, adapter, settings)
    owner = LOCAL_OWNER_ID

    try:
        run = service.start(owner, f"{profile}_{template}_photo", None,
                            None if job == "screenshot" else job, job == "screenshot")
        service.run_ingest(owner, run.run_id)
        run = repo.get_run(owner, run.run_id) or run
        if run.state is not RunState.waiting_for_user:
            raise SystemExit(f"Stopped: reading the CV failed ({run.error}).")
        now = datetime.now(UTC)
        for fact in repo.current_facts(owner, run.document_id):
            confirm(repo, owner, FactRef(fact_id=fact.fact_id, version=fact.version), now)
        service.continue_after_review(owner, run.run_id)
        _stop_unless_passed(service, run.run_id)

        run = repo.get_run(owner, run.run_id) or run
        facts = [f for f in repo.current_facts(owner, run.document_id)
                 if f.status is FactStatus.confirmed]
        fact = _inflatable_fact(facts)
        text = inflated_text(fact.attributes.title or "")
        result = service.try_claim(owner, run.run_id, text,
                                   [FactRef(fact_id=fact.fact_id, version=fact.version)])
    except StageError as exc:
        raise SystemExit(f"Stopped: {exc.code}: {exc.detail}") from None
    if result.outcome is not ClaimOutcome.rejected:
        raise SystemExit(f"Stopped: the inflated claim was {result.outcome.value}, not rejected.")

    with tempfile.TemporaryDirectory() as temp:
        stage = Path(temp)
        shutil.copyfile(cv_photo_path(profile, template), stage / "input_cv_photo.jpg")
        shutil.copyfile(JOB_SCREENSHOT, stage / "job_ad_screenshot.png")
        shutil.copyfile(RESULTS, stage / "RESULTS.md")
        (stage / "facts.json").write_text(_dump(list(facts)), encoding="utf-8")
        rows = repo.get_coverage(owner, run.target_id or "") or []
        (stage / "coverage.json").write_text(_dump(list(rows)), encoding="utf-8")
        (stage / "coverage.md").write_text(
            _coverage_table(json.loads(_dump(list(rows)))), encoding="utf-8")
        report = repo.get_report(owner, run.plan_id or "")
        if report is None:
            raise SystemExit("Stopped: the run has no validation report.")
        (stage / "validation_report.json").write_text(
            report.model_dump_json(indent=2) + "\n", encoding="utf-8")
        for oid in run.output_ids:
            output = repo.get_output(owner, oid)
            for name in OUTPUT_FILES[output.output_type] if output is not None else []:
                # output_file returns a path only for a file that passed verification.
                source = service.output_file(owner, oid, name)
                if source is None:
                    raise SystemExit(f"Stopped: {name} is not available for export.")
                shutil.copyfile(source, stage / name)
        (stage / "inflated_claim_rejected.md").write_text(
            _inflated_report(text, fact, result), encoding="utf-8")
        (stage / "README.md").write_text(
            FOLDER_README.format(profile=profile, template=template), encoding="utf-8")

        out.mkdir(parents=True, exist_ok=True)
        for name in EXPECTED_FILES:
            shutil.copyfile(stage / name, out / name)
    print(f"wrote {len(EXPECTED_FILES)} files to {out}")


if __name__ == "__main__":
    build_examples()
